// The "how age grading works" graphs on the About Age Grading page: inline
// SVG drawn from a snapshot of the 2025 road standards (WMA/USATF, Alan
// Jones) rather than fetched, since the age grading API is admin-only and a
// published table version never changes.

// Reports where the pointer is over an <svg>, in viewBox units, so a graph
// can show a readout under the mouse or a finger: agx-pointer="fn($point)",
// $point null once it leaves.
angular.module('mcrrcApp.tools').directive('agxPointer', function () {
    return {
        restrict: 'A',
        link: function (scope, element, attrs) {
            var svg = element[0];

            function report(point) {
                scope.$apply(function () {
                    scope.$eval(attrs.agxPointer, { $point: point });
                });
            }

            function move(event) {
                var source = event.touches ? event.touches[0] : event;
                var box = svg.getBoundingClientRect();
                var view = svg.viewBox.baseVal;
                if (!source || !box.width) return;
                report({
                    x: view.x + (source.clientX - box.left) / box.width * view.width,
                    y: view.y + (source.clientY - box.top) / box.height * view.height
                });
            }

            function leave() {
                report(null);
            }

            svg.addEventListener('mousemove', move);
            svg.addEventListener('mouseleave', leave);
            svg.addEventListener('touchstart', move, { passive: true });
            svg.addEventListener('touchmove', move, { passive: true });

            scope.$on('$destroy', function () {
                svg.removeEventListener('mousemove', move);
                svg.removeEventListener('mouseleave', leave);
                svg.removeEventListener('touchstart', move);
                svg.removeEventListener('touchmove', move);
            });
        }
    };
});

